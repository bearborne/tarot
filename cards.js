// ───────────────────────────────────────────────────────────────
//  YOUR DECK
//  Each card sits between { and }, followed by a comma.
//
//    name    – the card's title
//    image   – the picture file inside the "cards" folder
//              (leave it as "" to show just the name)
//    court   – true for the Pages, Knights, Queens and Kings: they are
//              only in the deck when "Court cards" is turned on
//    tags    – the card's tags, using the names from tags.js,
//              e.g. ["dawnbringer", "crossroads"]
//    keywords – a few words that sum the card up,
//              e.g. ["beginnings", "trust"]
//    correspondences – astrology, element and number
//              (Golden Dawn system); leave any of them out to hide it
//    short   – a short description of the card, shown in the card
//              window and on its page
//    reversed – what the card means when it comes out upside down
//    reversedKeywords – a few words for the card reversed (every card
//              has its own; without them it falls back to keywords)
//    reversedQuestions – only on cards whose questions don't fit both
//              ways; the rest use the same questions upright and reversed
//    ideas, nuances – key ideas for the card upright, one per line:
//              ideas are the warm, growth-minded ones; nuances are
//              neutral, or depend on how they're framed
//    reversedIdeas, reversedNuances – the same, for the card reversed
//    questions – questions the card asks you, one per line
//    line    – a short line to carry with you, shown on the card's page
//    story   – the card's scene in its journey (the Fool's journey for the
//              Majors; Ace to King for each suit), with what it comes from
//              (the card before) and leads to (the next)
//    inReading – short lines for the card's page and the summary:
//              upright, reversed, advice, challenge, action (what to do),
//              feeling (how it feels inside), you (the part of you it is),
//              each with a reversed… version for the card upside down
//    picture – what's in the picture: "The thing: what it means", one per line
//    details – the longer page, shown under "More about this card".
//              Leave an empty line between paragraphs.
//
//  Text goes between ` backticks ` so it can span several lines.
//
//  Pictures: the original 1909 Rider-Waite-Smith deck, drawn by
//  Pamela Colman Smith (public domain), scans from Wikimedia Commons.
